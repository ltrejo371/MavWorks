ALTER TABLE listings ADD COLUMN appointment_duration_minutes INTEGER NOT NULL DEFAULT 30;
ALTER TABLE listings ADD CONSTRAINT listings_appointment_duration_check
    CHECK (appointment_duration_minutes BETWEEN 5 AND 480);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
    buyer_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED', 'CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT bookings_positive_duration CHECK (end_at > start_at)
);
CREATE INDEX idx_bookings_listing_time_status ON bookings(listing_id, status, start_at, end_at);
CREATE INDEX idx_bookings_buyer_time ON bookings(buyer_id, start_at);
