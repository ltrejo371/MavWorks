INSERT INTO conversations (buyer_id, listing_id)
    SELECT DISTINCT b.buyer_id, b.listing_id FROM bookings b
    WHERE NOT EXISTS (SELECT 1 FROM conversations c WHERE c.buyer_id = b.buyer_id AND c.listing_id = b.listing_id);
UPDATE bookings SET conversation_id = (SELECT MAX(c.id) FROM conversations c
    WHERE c.buyer_id = bookings.buyer_id AND c.listing_id = bookings.listing_id);
