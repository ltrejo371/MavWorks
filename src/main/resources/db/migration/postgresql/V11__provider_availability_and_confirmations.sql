CREATE TABLE availability_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT availability_slots_positive_duration CHECK (end_at > start_at),
    CONSTRAINT uq_availability_listing_start UNIQUE (listing_id, start_at)
);
CREATE INDEX idx_availability_listing_time ON availability_slots(listing_id, start_at);

