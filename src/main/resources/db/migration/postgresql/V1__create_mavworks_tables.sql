-- Flyway selects the mavworks schema before running this migration.
-- Do not add mavworks to Supabase's exposed Data API schemas.
CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    hashed_password VARCHAR(255) NOT NULL,
    name VARCHAR(255),
    bio VARCHAR(2000),
    profile_picture_url VARCHAR(255),
    contact_information VARCHAR(255)
);

CREATE TABLE terms_of_service (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(255) NOT NULL UNIQUE,
    content TEXT NOT NULL,
    effective_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE tos_agreements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    terms_id BIGINT NOT NULL REFERENCES terms_of_service(id),
    accepted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_tos_agreements_user ON tos_agreements(user_id);
CREATE INDEX idx_tos_agreements_terms ON tos_agreements(terms_id);

CREATE TABLE listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users(id),
    name VARCHAR(255) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    type VARCHAR(255) NOT NULL CHECK (type IN ('PRODUCT', 'SERVICE')),
    category VARCHAR(255) NOT NULL CHECK (category IN ('OTHER')),
    status VARCHAR(255) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'UNAVAILABLE'))
);
CREATE INDEX idx_listings_owner ON listings(owner_id);
CREATE INDEX idx_listings_status_created ON listings(status, created_at);

CREATE TABLE listing_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_reference VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL,
    -- Nullable because the unidirectional JPA association sets this after insertion.
    listing_id BIGINT REFERENCES listings(id)
);
CREATE INDEX idx_listing_images_listing ON listing_images(listing_id);
