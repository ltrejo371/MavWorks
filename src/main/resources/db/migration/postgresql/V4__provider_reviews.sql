CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
    sale_confirmed_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT conversations_completion_order CHECK
        (sale_confirmed_at IS NULL OR closed_at IS NULL OR closed_at >= sale_confirmed_at)
);
CREATE INDEX idx_conversations_buyer_listing ON conversations(buyer_id, listing_id);
CREATE INDEX idx_conversations_listing ON conversations(listing_id);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT reviews_author_listing_unique UNIQUE (author_id, listing_id)
);
CREATE INDEX idx_reviews_listing ON reviews(listing_id);
