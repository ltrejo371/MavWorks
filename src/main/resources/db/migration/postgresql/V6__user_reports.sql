CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    reported_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    category VARCHAR(255) NOT NULL CHECK (category IN
        ('SCAM_OR_FRAUD', 'HARASSMENT', 'SPAM', 'INAPPROPRIATE_CONTENT', 'PROHIBITED_ITEMS', 'IMPERSONATION', 'OTHER')),
    reason VARCHAR(4000),
    status VARCHAR(255) NOT NULL CHECK (status IN ('PENDING', 'VALID', 'INVALID')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_reports_pending ON reports(status, created_at, id);
CREATE INDEX idx_reports_reporter ON reports(reporter_id);
CREATE INDEX idx_reports_reported_user ON reports(reported_user_id);
